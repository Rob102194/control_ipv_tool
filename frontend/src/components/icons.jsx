// Mapea el nombre de un área a un icono representativo, con un icono por
// defecto para áreas cuyo nombre no reconocemos (son datos del usuario).
export function iconoDeArea(nombreArea) {
  const nombre = (nombreArea || '').trim().toUpperCase();
  if (nombre.includes('BAR')) return GlassIcon;
  if (nombre.includes('CALIENTE') || nombre.includes('COCINA')) return FlameIcon;
  if (nombre.includes('PARRILLA') || nombre.includes('GRILL')) return GridIcon;
  if (nombre.includes('LUNCH') || nombre.includes('COMIDA')) return SunIcon;
  return BoxIcon;
}
